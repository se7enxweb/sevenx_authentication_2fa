// @description Generate a skeleton OAuth handler class and INI block for a provider.

require_once 'autoload.php';

$script = eZScript::instance(
    array(
        'description' => "sevenx_authentication_2fa OAuth handler skeleton builder\n" .
                         "Generates a new OAuth login handler for a given provider.\n",
        'use-session' => false,
        'use-modules' => false,
        'use-extensions' => true
    )
);

$script->startup();

$options = $script->getOptions(
    "[provider:][client-id:][client-secret:][authorization-url:][token-url:][userinfo-url:][scope:][ini-only][class-only]",
    "",
    array(
        'provider'          => 'Provider key, e.g. MyProvider (alphanumeric, no spaces)',
        'client-id'         => 'OAuth application client id',
        'client-secret'     => 'OAuth application client secret',
        'authorization-url' => 'OAuth authorization endpoint URL',
        'token-url'         => 'OAuth token endpoint URL',
        'userinfo-url'      => 'URL that returns the authenticated user profile',
        'scope'             => 'Space-separated OAuth scopes',
        'ini-only'          => 'Only update the INI file, do not generate the class',
        'class-only'        => 'Only generate the class file, do not update the INI file',
    )
);

$script->initialize();
$cli = eZCLI::instance();

if ( !$options['provider'] )
{
    $cli->error( 'The --provider argument is required.' );
    $script->shutdown( 1 );
}

$provider = preg_replace( '/[^a-zA-Z0-9_-]/', '', $options['provider'] );
if ( $provider !== $options['provider'] )
{
    $cli->warning( 'Provider name sanitized to: ' . $provider );
}

$providerUc = ucfirst( $provider );
$providerLc = strtolower( $provider );
$extensionDir = __DIR__ . '/../..';
$classFile    = $extensionDir . '/login_handler/ez' . $providerLc . 'user.php';
$iniFile      = $extensionDir . '/settings/sevenxauthentication2fa.ini.append.php';

// ---------------------------------------------------------------------------
// Generate class skeleton
// ---------------------------------------------------------------------------
if ( !$options['ini-only'] )
{
    $classSkeleton = <<<PHP
<?php
//
// sevenx_authentication_2fa - 7x Two-Factor and Social Authentication extension
// Copyright (C) 1998 - 2026 7x. All rights reserved.
//
// This program is free software; you can redistribute it and/or modify
// it under the terms of the GNU General Public License as published by
// the Free Software Foundation; either version 2 of the License, or
// (at your option) any later version.
//

/*!
  \\class eZ{$providerUc}User ez{$providerLc}user.php
  \\ingroup sevenx_authentication_2fa
  \\brief {$providerUc} OAuth 2.0 login handler.

  Generated by sevenx2fabuild.php. Customize normalizeUserInfo() and any
  provider-specific endpoints as needed.
*/
class eZ{$providerUc}User extends eZOAuthUser
{
    protected \$provider = '{$providerLc}';

    /**
     * Normalize the provider userinfo response to the common keys:
     *   id, email, name
     * @param array \$info
     * @return array
     */
    protected function normalizeUserInfo( \$info )
    {
        return array(
            'id'    => isset( \$info['id'] )    ? \$info['id']    : '',
            'email' => isset( \$info['email'] ) ? \$info['email'] : '',
            'name'  => isset( \$info['name'] )  ? \$info['name']  : '',
        );
    }

    protected function fetchUserInfo( \$token )
    {
        \$info = parent::fetchUserInfo( \$token );
        if ( !\$info )
            return false;
        return \$this->normalizeUserInfo( \$info );
    }
}
PHP;

    if ( file_exists( $classFile ) )
    {
        $cli->warning( "Class file already exists: $classFile" );
    }
    else
    {
        file_put_contents( $classFile, $classSkeleton );
        $cli->output( "Generated class file: $classFile" );
    }
}

// ---------------------------------------------------------------------------
// Generate INI block
// ---------------------------------------------------------------------------
if ( !$options['class-only'] )
{
    $clientId     = $options['client-id']         ? $options['client-id']         : '';
    $clientSecret = $options['client-secret']     ? $options['client-secret']     : '';
    $authUrl      = $options['authorization-url'] ? $options['authorization-url'] : '';
    $tokenUrl     = $options['token-url']         ? $options['token-url']         : '';
    $userinfoUrl  = $options['userinfo-url']      ? $options['userinfo-url']      : '';
    $scope        = $options['scope']             ? $options['scope']             : 'email profile';

    $iniBlock = <<<INI

[{$providerUc}]
Enabled=disabled
ClientID={$clientId}
ClientSecret={$clientSecret}
Scope={$scope}
AuthorizationURL={$authUrl}
TokenURL={$tokenUrl}
UserInfoURL={$userinfoUrl}
INI;

    $existing = file_get_contents( $iniFile );
    if ( strpos( $existing, '[' . $providerUc . ']' ) !== false )
    {
        $cli->warning( "INI block [$providerUc] already exists in $iniFile" );
    }
    else
    {
        // Trim the closing PHP wrapper before appending.
        $existing = preg_replace( '@\s*\*/\s*\?>\s*$@', '', $existing );
        $existing = rtrim( $existing ) . "\n" . $iniBlock . "\n\n*/ ?>\n";
        file_put_contents( $iniFile, $existing );
        $cli->output( "Appended INI block [$providerUc] to: $iniFile" );
    }
}

$cli->output( "Done. Remember to activate the extension and add the handler to your site.ini override if needed." );
$script->shutdown( 0 );
